const assert=require('node:assert/strict');
const fs=require('node:fs');
const logic=require('../assets/js/agenda.js');
const {selectListings}=require('../assets/js/guides.js');
const data=JSON.parse(fs.readFileSync(new URL('../data/agenda.json','file://'+__filename)));
const now={date:'2026-11-17',time:'22:00',day:2};
assert.deepEqual(logic.localNow(new Date('2026-11-17T17:30:00Z')),{date:'2026-11-18',time:'01:30',day:3},'Lombok day must advance ahead of UTC');
const breath=selectListings(data,'Breathwork',now,logic);
assert(breath.events.some(x=>x.id==='zora-breathwork-20261118'),'A Workshop must appear on the Breathwork guide');
assert(!breath.events.some(x=>x.id==='zora-brunch-20261121'),'Yoga brunch must not be presented as breathwork');
assert(!selectListings(data,'Meditation',now,logic).events.some(x=>x.id.startsWith('mana-mini-')),'Do not infer a programme component from a provider category');
assert(selectListings(data,'Sound healing',now,logic).weekly.some(x=>x.id==='flowers-sound'),'Include the explicitly tagged sound session');
const later={date:'2026-11-23',time:'10:00',day:1};
assert.equal(selectListings(data,'Sound healing',later,logic).weekly.length,0,'Remove expired weekly source times');
assert(!selectListings(data,'Breathwork',later,logic).events.some(x=>x.id==='zora-breathwork-20261118'),'Remove past workshops');
assert(selectListings(data,'Retreats',later,logic).events.some(x=>x.id==='xanadu-2026-11-21'),'Keep an ongoing multi-day retreat');
assert(!selectListings(data,'Retreats',{date:'2026-11-29',time:'01:00'},logic).events.some(x=>x.id==='xanadu-2026-11-21'),'Remove completed multi-day retreats');
assert(!logic.isUpcoming({date:'2026-11-17',endTime:'18:00'},now),'Remove today’s event after its end time');
assert.equal(selectListings(data,'Massage',now,logic).events.length,0,'Do not invent massage events from other provider services');
assert.equal(selectListings(data,'Reiki',now,logic).weekly.length,0,'Do not invent weekly Reiki times');
assert(logic.matchesPractice({type:'Yoga'},'Yoga'),'Legacy type remains a fallback');
assert(!logic.matchesPractice({type:'Workshop',practices:['Breathwork']},'Yoga'));
console.log('14 agenda checks passed: practice tags, WITA, expiry, ongoing retreats and honest empty states.');
